#!/usr/bin/env python3
"""Audit matrix Schur coordinates for the repeated-Crabb transfer.

Near the monomial inner function ``z**L U``, a square degree-``L``
matrix inner function is generated by Schur parameters
``Gamma_0, ..., Gamma_(L-1)`` and a terminal unitary.  The
repeated-Crabb transfer has ``Gamma_0=0``.  This checker verifies the
ordered matrix linear-fractional recursion, its inverse on L201
transfer series, and the exact tangent pairing at the monomial.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
import json
from pathlib import Path

import numpy as np
from scipy.linalg import sqrtm

from crabb_block_hardy_equality import format_float
from repeated_crabb_inner_faber_transfer import (
    canonical_transfer_data,
    strengthened_inverse_toeplitz,
    transfer_coefficients,
)


MatrixSeries = list[np.ndarray]


@dataclass(frozen=True)
class MatrixSchurChartRecord:
    """One matrix Schur/transfer chart audit."""

    construction_kind: str
    length: int
    multiplicity: int
    toeplitz_strength: str
    maximum_parameter_norm: str
    forced_zero_parameter_error: str
    terminal_unitary_error: str
    terminal_tail_error: str
    coefficient_roundtrip_error: str
    circle_inner_error: str
    schur_kernel_identity_error: str
    monomial_tangent_error: str
    all_checks_passed: bool


def series_multiply(
    left: MatrixSeries,
    right: MatrixSeries,
) -> MatrixSeries:
    """Multiply square matrix series to their common truncation."""

    count = min(len(left), len(right))
    result = [np.zeros_like(left[0]) for _ in range(count)]
    for left_degree, left_coefficient in enumerate(left[:count]):
        for right_degree, right_coefficient in enumerate(right[:count]):
            degree = left_degree + right_degree
            if degree < count:
                result[degree] += left_coefficient @ right_coefficient
    return result


def inverse_series(series: MatrixSeries) -> MatrixSeries:
    """Invert a square matrix series with invertible constant term."""

    result = [np.linalg.inv(series[0])]
    for degree in range(1, len(series)):
        convolution = np.zeros_like(series[0])
        for positive_degree in range(1, degree + 1):
            convolution += (
                series[positive_degree]
                @ result[degree - positive_degree]
            )
        result.append(-result[0] @ convolution)
    return result


def defect_roots(
    parameter: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Return the ordered left and right Schur defect roots."""

    multiplicity = len(parameter)
    identity = np.eye(multiplicity, dtype=complex)
    left = np.asarray(
        sqrtm(identity - parameter @ parameter.conj().T),
        dtype=complex,
    )
    right = np.asarray(
        sqrtm(identity - parameter.conj().T @ parameter),
        dtype=complex,
    )
    return left, right


def forward_schur_step(
    parameter: np.ndarray,
    next_series: MatrixSeries,
) -> MatrixSeries:
    """Apply one ordered matrix Schur linear-fractional step."""

    count = len(next_series)
    multiplicity = len(parameter)
    identity = np.eye(multiplicity, dtype=complex)
    left, right = defect_roots(parameter)
    shifted = [np.zeros_like(parameter)] + next_series[:-1]
    denominator = [identity.copy()] + [
        np.zeros_like(parameter) for _ in range(count - 1)
    ]
    for degree, coefficient in enumerate(shifted):
        denominator[degree] += parameter.conj().T @ coefficient
    quotient = series_multiply(
        shifted,
        inverse_series(denominator),
    )
    result = [
        left @ coefficient @ right
        for coefficient in quotient
    ]
    result[0] += parameter
    return result


def inverse_schur_step(
    series: MatrixSeries,
) -> tuple[np.ndarray, MatrixSeries]:
    """Recover one Schur parameter and the next matrix series."""

    parameter = series[0]
    multiplicity = len(parameter)
    identity = np.eye(multiplicity, dtype=complex)
    left, right = defect_roots(parameter)
    numerator = [coefficient.copy() for coefficient in series]
    numerator[0] -= parameter
    denominator = [
        -parameter.conj().T @ coefficient
        for coefficient in series
    ]
    denominator[0] += identity
    quotient = series_multiply(
        numerator,
        inverse_series(denominator),
    )
    inverse_left = np.linalg.inv(left)
    shifted = [
        inverse_left @ coefficient @ right
        for coefficient in quotient
    ]
    next_series = shifted[1:] + [np.zeros_like(parameter)]
    return parameter, next_series


def reconstruct_series(
    parameters: list[np.ndarray],
    terminal: np.ndarray,
    count: int,
) -> MatrixSeries:
    """Reconstruct a truncated matrix inner series."""

    series = [terminal] + [
        np.zeros_like(terminal) for _ in range(count - 1)
    ]
    for parameter in reversed(parameters):
        series = forward_schur_step(parameter, series)
    return series


def schur_value(
    parameters: list[np.ndarray],
    terminal: np.ndarray,
    value: complex,
) -> np.ndarray:
    """Evaluate the exact nested Schur recursion."""

    function_value = terminal
    identity = np.eye(len(terminal), dtype=complex)
    for parameter in reversed(parameters):
        left, right = defect_roots(parameter)
        shifted = value * function_value
        function_value = (
            parameter
            + left
            @ shifted
            @ np.linalg.inv(
                identity + parameter.conj().T @ shifted
            )
            @ right
        )
    return function_value


def one_step_kernel_error(
    multiplicity: int,
    seed: int,
) -> float:
    """Audit the ordered matrix Schur kernel identity."""

    generator = np.random.default_rng(seed)

    def random_contraction(radius: float) -> np.ndarray:
        matrix = (
            generator.standard_normal((multiplicity, multiplicity))
            + 1j
            * generator.standard_normal((multiplicity, multiplicity))
        )
        return radius * matrix / np.linalg.norm(matrix, ord=2)

    parameter = random_contraction(0.31)
    left_value = random_contraction(0.47)
    right_value = random_contraction(0.43)
    left_defect, right_defect = defect_roots(parameter)
    identity = np.eye(multiplicity, dtype=complex)

    def transform(value: np.ndarray) -> np.ndarray:
        return (
            parameter
            + left_defect
            @ value
            @ np.linalg.inv(identity + parameter.conj().T @ value)
            @ right_defect
        )

    transformed_left = transform(left_value)
    transformed_right = transform(right_value)
    actual = identity - transformed_left.conj().T @ transformed_right
    expected = (
        right_defect
        @ np.linalg.inv(
            identity + left_value.conj().T @ parameter
        )
        @ (identity - left_value.conj().T @ right_value)
        @ np.linalg.inv(
            identity + parameter.conj().T @ right_value
        )
        @ right_defect
    )
    return float(np.linalg.norm(actual - expected))


def recover_parameters(
    series: MatrixSeries,
    length: int,
) -> tuple[list[np.ndarray], np.ndarray, MatrixSeries]:
    """Run ``length`` inverse Schur steps."""

    parameters: list[np.ndarray] = []
    remainder = [coefficient.copy() for coefficient in series]
    for _ in range(length):
        parameter, remainder = inverse_schur_step(remainder)
        parameters.append(parameter)
    return parameters, remainder[0], remainder


def tangent_error(
    length: int,
    multiplicity: int,
    terminal: np.ndarray,
    seed: int,
) -> float:
    """Check the exact monomial tangent pairing by finite difference."""

    generator = np.random.default_rng(seed)
    direction = (
        generator.standard_normal((multiplicity, multiplicity))
        + 1j
        * generator.standard_normal((multiplicity, multiplicity))
    )
    zero = np.zeros_like(terminal)
    parameters = [zero.copy() for _ in range(length)]
    step = 2e-7
    maximum_error = 0.0
    for index in range(1, length):
        plus = [parameter.copy() for parameter in parameters]
        minus = [parameter.copy() for parameter in parameters]
        plus[index] = step * direction
        minus[index] = -step * direction
        for sample in range(7):
            value = 0.71 * np.exp(
                2j * np.pi * (sample + 0.19) / 7
            )
            numerical = (
                schur_value(plus, terminal, value)
                - schur_value(minus, terminal, value)
            ) / (2 * step)
            expected = (
                value**index * direction
                - value ** (2 * length - index)
                * terminal
                @ direction.conj().T
                @ terminal
            )
            maximum_error = max(
                maximum_error,
                float(np.linalg.norm(numerical - expected)),
            )
    return maximum_error


def audit_transfer(
    construction_kind: str,
    length: int,
    multiplicity: int,
    inverse_toeplitz: np.ndarray,
    strength: float,
    seed: int,
) -> MatrixSchurChartRecord:
    """Recover and reconstruct one L201 transfer."""

    hermitian = np.linalg.inv(inverse_toeplitz)
    data = canonical_transfer_data(
        hermitian,
        length,
        multiplicity,
    )
    count = max(80, 12 * length)
    original = list(transfer_coefficients(data, count))
    parameters, terminal, remainder = recover_parameters(
        original,
        length,
    )
    reconstructed = reconstruct_series(
        parameters,
        terminal,
        count,
    )
    safe_count = count - length - 2
    roundtrip_error = max(
        float(np.linalg.norm(original[index] - reconstructed[index]))
        for index in range(safe_count)
    )
    terminal_unitary_error = float(
        np.linalg.norm(
            terminal.conj().T @ terminal
            - np.eye(multiplicity)
        )
    )
    terminal_tail_error = max(
        float(np.linalg.norm(coefficient))
        for coefficient in remainder[1:safe_count]
    )
    circle_error = 0.0
    for index in range(29):
        value = np.exp(2j * np.pi * (index + 0.27) / 29)
        evaluated = schur_value(parameters, terminal, value)
        circle_error = max(
            circle_error,
            float(
                np.linalg.norm(
                    evaluated.conj().T @ evaluated
                    - np.eye(multiplicity)
                )
            ),
        )
    tangent = tangent_error(
        length,
        multiplicity,
        terminal,
        seed,
    )
    kernel_error = one_step_kernel_error(
        multiplicity,
        seed + 100_000,
    )
    forced_zero_error = float(np.linalg.norm(parameters[0]))
    maximum_parameter = max(
        float(np.linalg.norm(parameter, ord=2))
        for parameter in parameters
    )
    tolerance = 3e-7
    verified = bool(
        forced_zero_error < tolerance
        and terminal_unitary_error < tolerance
        and terminal_tail_error < tolerance
        and roundtrip_error < tolerance
        and circle_error < tolerance
        and kernel_error < tolerance
        and tangent < tolerance
        and all(
            np.linalg.norm(parameter, ord=2) < 1
            for parameter in parameters
        )
    )
    if not verified:
        raise RuntimeError(
            "matrix Schur chart audit failed: "
            f"zero={forced_zero_error:.3e}, "
            f"unitary={terminal_unitary_error:.3e}, "
            f"tail={terminal_tail_error:.3e}, "
            f"roundtrip={roundtrip_error:.3e}, "
            f"circle={circle_error:.3e}, "
            f"kernel={kernel_error:.3e}, tangent={tangent:.3e}"
        )
    return MatrixSchurChartRecord(
        construction_kind=construction_kind,
        length=length,
        multiplicity=multiplicity,
        toeplitz_strength=format_float(strength),
        maximum_parameter_norm=format_float(maximum_parameter),
        forced_zero_parameter_error=format_float(forced_zero_error),
        terminal_unitary_error=format_float(terminal_unitary_error),
        terminal_tail_error=format_float(terminal_tail_error),
        coefficient_roundtrip_error=format_float(roundtrip_error),
        circle_inner_error=format_float(circle_error),
        schur_kernel_identity_error=format_float(kernel_error),
        monomial_tangent_error=format_float(tangent),
        all_checks_passed=verified,
    )


def standard_records() -> list[MatrixSchurChartRecord]:
    """Return deterministic apex and noncommuting equality records."""

    records: list[MatrixSchurChartRecord] = []
    for length in range(2, 6):
        for multiplicity in (2, 3):
            inverse, strength = strengthened_inverse_toeplitz(
                length,
                multiplicity,
                0.22,
            )
            records.append(
                audit_transfer(
                    "noncommuting_inverse_block_toeplitz",
                    length,
                    multiplicity,
                    inverse,
                    strength,
                    718_000 + 10 * length + multiplicity,
                )
            )
            apex_inverse = 2 * np.eye(
                length * multiplicity,
                dtype=complex,
            )
            records.append(
                audit_transfer(
                    "repeated_crabb_apex",
                    length,
                    multiplicity,
                    apex_inverse,
                    0.0,
                    719_000 + 10 * length + multiplicity,
                )
            )
    return records


def write_records(
    records: list[MatrixSchurChartRecord],
    output: Path,
) -> None:
    """Write deterministic JSON Lines atomically."""

    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8") as stream:
        for record in records:
            stream.write(json.dumps(asdict(record), sort_keys=True) + "\n")
    temporary.replace(output)


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "experiments/"
            "repeated_crabb_matrix_schur_chart_s70224.jsonl"
        ),
    )
    return parser.parse_args()


def main() -> None:
    """Run the complete matrix Schur chart audit."""

    args = parse_args()
    records = standard_records()
    write_records(records, args.output)
    for record in records:
        print(json.dumps(asdict(record), sort_keys=True))


if __name__ == "__main__":
    main()
