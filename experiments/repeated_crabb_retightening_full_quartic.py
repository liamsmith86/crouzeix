Matrix = np.ndarray


@dataclass(frozen=True)
class FullQuarticRecord:
    """One complete upper/lower Schur-endpoint audit."""

    construction_kind: str
    state_dimension: int
    defect_dimension: int
    parameter_scale: str
    retightening_scale: str
    first_transfer_norm: str
    second_transfer_norm: str
    cubic_weighted_pairing_absolute: str
    lower_quartic_delta_error: str
    upper_quartic_weighted_pairing: str
    predicted_upper_quartic_weighted_pairing: str
    upper_quartic_weighted_error: str
    neutralized_lower_quartic_norm: str
    neutralized_upper_weighted_pairing: str
    predicted_neutralized_upper_weighted_pairing: str
    neutralized_upper_weighted_error: str
    prior_flag_representative_compression_norm: str
    observability_commutator_error: str
    exact_lower_delta_residual_words: int
    exact_upper_delta_cyclic_residual_classes: int
    exact_neutralized_upper_cyclic_residual_classes: int
    all_checks_passed: bool


def cross_square_delta(
    base_cross: Polynomial,
    change_cross: Polynomial,
    interior_inverse: Polynomial,
) -> Polynomial:
    """Return the change of ``cross inverse cross*``."""

    return add(
        multiply(
            multiply(base_cross, interior_inverse),
            adjoint(change_cross),
        ),
        multiply(
            multiply(change_cross, interior_inverse),
            adjoint(base_cross),
        ),
        multiply(
            multiply(change_cross, interior_inverse),
            adjoint(change_cross),
        ),
    )


def right_gram_lift() -> Polynomial:
    """Return the state lift ``V(B_1*B_1)V*``."""

    return multiply(
        multiply(
            multiply(
                multiply(E, S),
                F,
            ),
            STAR,
        ),
        E,
    )


def exact_residuals_at_scale(
    retightening_scale: Fraction,
) -> tuple[int, int, int]:
    """Return exact endpoint residuals at one rational scale."""

    theta = retightening_scale
    components = exact_quartic_components()
    second_metric = add(
        boundary_metric_series(DEGREE)[2],
        scale(-1, schur_residual_series(DEGREE)[2]),
    )

    right_complement = multiply(STAR, S)
    lower_inverse = add(
        scale(2, right_complement),
        scale(Fraction(-2, 3), F),
    )
    lower_base_cross = multiply(
        multiply(E, second_metric),
        right_complement,
    )
    lower_change_cross = scale(
        theta,
        multiply(
            multiply(E, components.metric),
            right_complement,
        ),
    )
    quadratic_forcing = scale(
        -1,
        multiply(components.frame, adjoint(components.frame)),
    )
    upper_quadratic_trace_lift = quadratic_forcing
    lower_quadratic_corner = multiply(
        multiply(E, quadratic_forcing),
        E,
    )
    scaled_lower_corner = add(
        scale(
            theta,
            add(
                components.lower_corner,
                scale(-1, lower_quadratic_corner),
            ),
        ),
        scale(theta * theta, lower_quadratic_corner),
    )
    lower_delta = add(
        scale(-1, scaled_lower_corner),
        scale(
            -1,
            cross_square_delta(
                lower_base_cross,
                lower_change_cross,
                lower_inverse,
            ),
        ),
    )
    first_right_gram = right_gram_lift()
    predicted_lower_delta = add(
        scale(
            -4 * theta - theta * theta / 2,
            first_right_gram,
        ),
        scale(
            -Fraction(9, 2) * theta
            + Fraction(3, 4) * theta * theta,
            multiply(first_right_gram, first_right_gram),
        ),
    )
    lower_residual = add(
        lower_delta,
        scale(-1, predicted_lower_delta),
    )

    left_complement = add(IDENTITY, scale(-1, F))
    upper_inverse = add(
        IDENTITY,
        scale(-1, F),
        scale(Fraction(-2, 3), E),
    )
    upper_base_cross = scale(
        -1,
        multiply(
            multiply(F, second_metric),
            left_complement,
        ),
    )
    upper_change_cross = scale(
        -theta,
        multiply(
            multiply(F, components.metric),
            left_complement,
        ),
    )
    scaled_direct_upper = add(
        scale(
            theta,
            add(
                components.effective_upper_trace_lift,
                scale(-1, upper_quadratic_trace_lift),
            ),
        ),
        scale(theta * theta, upper_quadratic_trace_lift),
    )
    balanced_upper_delta = add(
        scaled_direct_upper,
        scale(
            -1,
            cross_square_delta(
                upper_base_cross,
                upper_change_cross,
                upper_inverse,
            ),
        ),
    )
    first_left_gram = left_gram_lift()
    predicted_balanced_upper = add(
        scale(
            2 * theta - theta * theta / 2,
            first_left_gram,
        ),
        scale(
            Fraction(5, 2) * theta
            + theta * theta / 4,
            multiply(first_left_gram, first_left_gram),
        ),
    )
    upper_residual = cyclic_trace_classes(
        add(
            balanced_upper_delta,
            scale(-1, predicted_balanced_upper),
        )
    )

    lower_neutralizer_left = add(
        scale(
            4 * theta + theta * theta / 2,
            first_left_gram,
        ),
        scale(
            Fraction(9, 2) * theta
            - Fraction(3, 4) * theta * theta,
            multiply(first_left_gram, first_left_gram),
        ),
    )
    neutralized_upper = add(
        balanced_upper_delta,
        scale(-1, lower_neutralizer_left),
    )
    predicted_neutralized_upper = add(
        scale(-2 * theta - theta * theta, first_left_gram),
        scale(
            -2 * theta + theta * theta,
            multiply(first_left_gram, first_left_gram),
        ),
    )
    neutralized_residual = cyclic_trace_classes(
        add(
            neutralized_upper,
            scale(-1, predicted_neutralized_upper),
        )
    )
    return (
        len(lower_residual),
        len(upper_residual),
        len(neutralized_residual),
    )


@lru_cache(maxsize=1)
def exact_residuals() -> tuple[int, int, int]:
    """Audit the degree-two scale law at three exact values."""

    residuals = [
        exact_residuals_at_scale(theta)
        for theta in (
            Fraction(-1),
            Fraction(1, 2),
            Fraction(1),
        )
    ]
    return tuple(
        sum(residual[index] for residual in residuals)
        for index in range(3)
    )


def endpoint_series(
    metric: list[Matrix],
    equality_metric: Matrix,
    right: Matrix,
    left: Matrix,
) -> tuple[list[Matrix], list[Matrix]]:
    """Return physical upper and balanced lower Schur endpoints."""

    upper_target = 4 * np.linalg.inv(equality_metric)
    upper_gap = [upper_target - metric[0]] + [
        -coefficient for coefficient in metric[1:]
    ]
    lower_target = np.linalg.inv(equality_metric)
    lower_gap = [metric[0] - lower_target] + metric[1:]
    upper, upper_error = full_endpoint_gap_series(upper_gap, left)
    lower, lower_error = full_lower_endpoint_series(lower_gap, right)
    if max(upper_error, lower_error) > 3e-8:
        raise RuntimeError("the complete endpoint base was inconsistent")
    return [4 * coefficient for coefficient in upper], lower


def full_quartic_deltas(
    partial: Matrix,
    right: Matrix,
    left: Matrix,
    retightening_scale: float,
) -> tuple[
    list[Matrix],
    list[Matrix],
    list[Matrix],
    list[Matrix],
    Matrix,
    Matrix,
]:
    """Return raw, prepared, and lower-neutral complete endpoints."""

    components = numerical_quartic_components(
        partial,
        right,
        left,
    )
    raw_metric = [
        coefficient.copy() for coefficient in components.base_metric
    ]
    prepared_metric = [
        coefficient.copy() for coefficient in components.base_metric
    ]
    theta = retightening_scale
    prepared_metric[2] += theta * components.metric_two
    prepared_metric[3] += theta * components.metric_three
    prepared_metric[4] += (
        theta
        * (
            components.metric_four
            - components.metric_four_quadratic
        )
        + theta * theta * components.metric_four_quadratic
    )

    first = components.first_transfer
    right_gram = first.conj().T @ first
    lower_neutralizer = (
        (4 * theta + theta * theta / 2) * right_gram
        + (
            9 * theta / 2
            - 3 * theta * theta / 4
        )
        * right_gram
        @ right_gram
    )
    neutral_metric = [
        coefficient.copy() for coefficient in prepared_metric
    ]
    neutral_metric[4] += stein_inverse(
        partial,
        right @ lower_neutralizer @ right.conj().T,
    )

    raw_upper, raw_lower = endpoint_series(
        raw_metric,
        components.equality_metric,
        right,
        left,
    )
    prepared_upper, prepared_lower = endpoint_series(
        prepared_metric,
        components.equality_metric,
        right,
        left,
    )
    neutral_upper, neutral_lower = endpoint_series(
        neutral_metric,
        components.equality_metric,
        right,
        left,
    )
    return (
        [
            prepared - raw
            for prepared, raw in zip(
                prepared_upper,
                raw_upper,
                strict=True,
            )
        ],
        [
            prepared - raw
            for prepared, raw in zip(
                prepared_lower,
                raw_lower,
                strict=True,
            )
        ],
        [
            neutral - raw
            for neutral, raw in zip(
                neutral_upper,
                raw_upper,
                strict=True,
            )
        ],
        [
            neutral - raw
            for neutral, raw in zip(
                neutral_lower,
                raw_lower,
                strict=True,
            )
        ],
        first,
        lower_neutralizer,
    )


def stable_left_kernel(matrix: Matrix) -> Matrix:
    """Return a stable frame for ``ker(matrix*)``."""

    _, singular_values, adjoint = np.linalg.svd(
        matrix.conj().T,
        full_matrices=True,
    )
    tolerance = max(
        1e-10,
        1e-8 * singular_values[0] if len(singular_values) else 0,
    )
    rank = int(np.count_nonzero(singular_values > tolerance))
    return adjoint.conj().T[:, rank:]


def audit_case(
    construction_kind: str,
    partial: Matrix,
    right: Matrix,
    left: Matrix,
    parameter_scale: float,
    retightening_scale: float,
    weight: Matrix | None = None,
) -> FullQuarticRecord:
    """Audit one complete quartic endpoint difference."""

    (
        upper_delta,
        lower_delta,
        neutral_upper_delta,
        neutral_lower_delta,
        first,
        lower_neutralizer,
    ) = full_quartic_deltas(
        partial,
        right,
        left,
        retightening_scale,
    )
    if weight is None:
        weight = np.eye(right.shape[1], dtype=complex)

    observability = dual_stein_inverse(
        partial,
        left @ weight @ left.conj().T,
    )
    commutator_error = float(
        np.linalg.norm(
            observability @ partial - partial @ observability
        )
    )
    left_gram = first @ first.conj().T
    theta = retightening_scale
    expected_upper = (
        (8 * theta - 2 * theta * theta) * left_gram
        + (10 * theta + theta * theta)
        * left_gram
        @ left_gram
    )
    expected_neutral_upper = (
        (-8 * theta - 4 * theta * theta) * left_gram
        + (-8 * theta + 4 * theta * theta)
        * left_gram
        @ left_gram
    )
    upper_actual = float(np.trace(weight @ upper_delta[4]).real)
    upper_predicted = float(np.trace(weight @ expected_upper).real)
    upper_error = abs(upper_actual - upper_predicted)
    neutral_upper_actual = float(
        np.trace(weight @ neutral_upper_delta[4]).real
    )
    neutral_upper_predicted = float(
        np.trace(weight @ expected_neutral_upper).real
    )
    neutral_upper_error = abs(
        neutral_upper_actual - neutral_upper_predicted
    )
    lower_error = float(
        np.linalg.norm(lower_delta[4] + lower_neutralizer)
    )
    neutral_lower_norm = float(
        np.linalg.norm(neutral_lower_delta[4])
    )
    cubic_pairing = abs(
        float(np.trace(weight @ upper_delta[3]).real)
    )

    flag = stable_left_kernel(first)
    prior_representative = (
        (8 * theta + 4 * theta * theta) * left_gram
        + (8 * theta - 4 * theta * theta)
        * left_gram
        @ left_gram
    )
    prior_flag_error = float(
        np.linalg.norm(
            flag.conj().T @ prior_representative @ flag
        )
    )
    second = transfer_coefficient(partial, right, left, 2)
    exact = exact_residuals()
    tolerance = 1e-7
    verified = bool(
        commutator_error < tolerance
        and cubic_pairing < tolerance
        and lower_error < tolerance
        and upper_error < tolerance
        and neutral_lower_norm < tolerance
        and neutral_upper_error < tolerance
        and prior_flag_error < tolerance
        and exact == (0, 0, 0)
    )
    if not verified:
        raise RuntimeError(
            "the full-quartic endpoint audit failed: "
            f"{construction_kind=}, {commutator_error=}, "
            f"{cubic_pairing=}, {lower_error=}, {upper_error=}, "
            f"{neutral_lower_norm=}, {neutral_upper_error=}, "
            f"{prior_flag_error=}, {exact=}"
        )
    return FullQuarticRecord(
        construction_kind=construction_kind,
        state_dimension=len(partial),
        defect_dimension=right.shape[1],
        parameter_scale=format_float(parameter_scale),
        retightening_scale=format_float(retightening_scale),
        first_transfer_norm=format_float(float(np.linalg.norm(first))),
        second_transfer_norm=format_float(float(np.linalg.norm(second))),
        cubic_weighted_pairing_absolute=format_float(cubic_pairing),
        lower_quartic_delta_error=format_float(lower_error),
        upper_quartic_weighted_pairing=format_float(upper_actual),
        predicted_upper_quartic_weighted_pairing=format_float(
            upper_predicted
        ),
        upper_quartic_weighted_error=format_float(upper_error),
        neutralized_lower_quartic_norm=format_float(
            neutral_lower_norm
        ),
        neutralized_upper_weighted_pairing=format_float(
            neutral_upper_actual
        ),
        predicted_neutralized_upper_weighted_pairing=format_float(
            neutral_upper_predicted
        ),
        neutralized_upper_weighted_error=format_float(
            neutral_upper_error
        ),
        prior_flag_representative_compression_norm=format_float(
            prior_flag_error
        ),
        observability_commutator_error=format_float(commutator_error),
        exact_lower_delta_residual_words=exact[0],
        exact_upper_delta_cyclic_residual_classes=exact[1],
        exact_neutralized_upper_cyclic_residual_classes=exact[2],
        all_checks_passed=verified,
    )


def standard_records() -> list[FullQuarticRecord]:
    """Return deterministic general, flag, delay, and reducing records."""

    records: list[FullQuarticRecord] = []
    for multiplicity, theta in zip(
        range(1, 5),
        (0.25, 0.5, 0.75, 1.0),
        strict=True,
    ):
        partial, right, left = random_partial_isometry(
            3 * multiplicity + 3,
            multiplicity,
            np.random.default_rng(121_000 + multiplicity),
        )
        records.append(
            audit_case(
                "unstructured",
                partial,
                right,
                left,
                1,
                theta,
            )
        )

    for multiplicity in range(2, 6):
        for parameter_scale in (1.0, 0.3, 0.1):
            partial, right, left, _, _ = rank_chain_case(
                multiplicity,
                121_200 + multiplicity,
                parameter_scale,
            )
            records.append(
                audit_case(
                    "rank_chain",
                    partial,
                    right,
                    left,
                    parameter_scale,
                    0.5,
                )
            )

    generator = np.random.default_rng(121_500)
    for multiplicity in (2, 3, 4):
        partial, right, left = delayed_random_partial_isometry(
            4 * multiplicity,
            multiplicity,
            generator,
        )
        records.append(
            audit_case(
                "complete_first_delay",
                partial,
                right,
                left,
                1,
                0.5,
            )
        )

    for index in range(3):
        partial, right, left, weight = reducing_sum_case(
            121_700 + 2 * index
        )
        records.append(
            audit_case(
                "weighted_reducing_sum",
                partial,
                right,
                left,
                1,
                (0.25, 0.5, 0.75)[index],
                weight,
            )
        )
    return records


def write_records(
    records: list[FullQuarticRecord],
    output: Path,
) -> str:
    """Write deterministic JSON Lines atomically and return its hash."""

    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8") as stream:
        for record in records:
            stream.write(json.dumps(asdict(record), sort_keys=True) + "\n")
    temporary.replace(output)
    return hashlib.sha256(output.read_bytes()).hexdigest()


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "experiments/"
            "repeated_crabb_retightening_full_quartic_s70226.jsonl"
        ),
    )
    return parser.parse_args()


def main() -> None:
    """Run and persist the complete audit."""

    args = parse_args()
    records = standard_records()
    digest = write_records(records, args.output)
    for record in records:
        print(json.dumps(asdict(record), sort_keys=True))
    print(json.dumps({"sha256": digest}, sort_keys=True))


if __name__ == "__main__":
    main()
