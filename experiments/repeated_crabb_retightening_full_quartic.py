#!/usr/bin/env python3
"""Audit the complete Schur-endpoint effect through the quartic.

L302 computes the two endpoints of the quartic Stein correction.
This checker includes the Schur cross generated by L298's quadratic
metric direction and compares the resulting complete endpoint with
the raw canonical repair.

For retightening scale ``theta``, before lower neutralization the
quartic difference is

    lower:  -(4 theta + theta^2/2) A
            -(9 theta/2 - 3 theta^2/4) A^2,
    upper:  +(8 theta - 2 theta^2) L
            +(10 theta + theta^2) L^2       (physical gap).

where A=B_1*B_1 and L=B_1B_1*.  Adding the analytic parallel metric
for the negative lower face leaves

    lower:  0,
    upper:  -(8 theta + 4 theta^2) L
            -(8 theta - 4 theta^2) L^2.

The remaining upper cost is a prior-B_1 factor and vanishes on the
next surviving flag.  Exact word algebra proves the two quotient
identities; numerical reconstruction audits the full Schur series.
"""

