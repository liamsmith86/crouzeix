#!/usr/bin/env python3
"""Audit weighted bridge causality of the canonical frame cross.

The canonical repair factor has the graph formula

    D = H V (V* H V)^(-1/2),

where ``H=P_bl-A*P_bl A`` is the unrepaired boundary slack.  L298's
grade-k retightening column also has an explicit lift in the bridge
ideal generated by ``G_k=E S^k F``.  The two facts remove the apparent
weight obstruction caused by expanding the raw frame on its own.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
import hashlib
import json
from pathlib import Path

import numpy as np

from crabb_block_hardy_equality import format_float
from repeated_crabb_boundary_metric_flag import rank_chain_case
from repeated_crabb_canonical_quintic_preimage import (
    canonical_factor_series,
    canonical_metric_slack_and_operator,
)
from repeated_crabb_delayed_jet import series_multiply
from repeated_crabb_endpoint_null_gauge import (
    delayed_random_partial_isometry,
)
from repeated_crabb_one_image_generator import (
    boundary_metric_coefficient,
)
from repeated_crabb_oriented_retightening_transport import (
    oriented_retightening_direction,
)
from repeated_crabb_transfer_channel_covariance import (
    random_partial_isometry,
)


Matrix = np.ndarray
DEGREE = 8
MAXIMUM_GRADE = 6
PARAMETER = 0.23


@dataclass(frozen=True)
class FramePairingCausalityRecord:
    """One graph-factor and bridge-root audit."""

    construction_kind: str
    state_dimension: int
    defect_dimension: int
    parameter_scale: str
    graph_factor_error: str
    rooted_column_error: str
    complete_delay_column_error: str
    maximum_weighted_frame_ratio: str
    all_checks_passed: bool


def adjoint_series(series: list[Matrix]) -> list[Matrix]:
    """Return a coefficientwise adjoint series."""

    return [coefficient.conj().T for coefficient in series]


def identity_series(
    identity: Matrix,
    degree: int,
) -> list[Matrix]:
    """Return the constant identity series."""

    return [identity] + [
        np.zeros_like(identity) for _ in range(degree)
    ]


def square_root_series(series: list[Matrix]) -> list[Matrix]:
    """Return the principal square root of a series with constant I."""

    degree = len(series) - 1
    identity = np.eye(len(series[0]), dtype=complex)
    root = identity_series(identity, degree)
    for order in range(1, degree + 1):
        cross = np.zeros_like(identity)
        for left_degree in range(1, order):
            cross += root[left_degree] @ root[order - left_degree]
        root[order] = (series[order] - cross) / 2
    return root


def inverse_series(series: list[Matrix]) -> list[Matrix]:
    """Return the inverse of a series with identity constant term."""

    degree = len(series) - 1
    identity = np.eye(len(series[0]), dtype=complex)
    inverse = identity_series(identity, degree)
    for order in range(1, degree + 1):
        coefficient = np.zeros_like(identity)
        for left_degree in range(1, order + 1):
            coefficient += (
                series[left_degree] @ inverse[order - left_degree]
            )
        inverse[order] = -coefficient
    return inverse


def graph_factor_series(
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    degree: int,
) -> tuple[list[Matrix], list[Matrix], list[Matrix]]:
    """Return boundary slack, graph factor, and canonical factor."""

    identity = np.eye(len(operator), dtype=complex)
    _, repaired_slack, moving_operator, _ = (
        canonical_metric_slack_and_operator(
            operator,
            right,
            left,
            degree,
        )
    )
    boundary = [identity] + [
        boundary_metric_coefficient(
            operator,
            right,
            left,
            order,
        )
        for order in range(1, degree + 1)
    ]
    pulled = series_multiply(
        series_multiply(
            adjoint_series(moving_operator),
            boundary,
            degree,
        ),
        moving_operator,
        degree,
    )
    boundary_slack = [
        metric - image
        for metric, image in zip(boundary, pulled, strict=True)
    ]
    pivot = [
        right.conj().T @ coefficient @ right
        for coefficient in boundary_slack
    ]
    inverse_root = inverse_series(square_root_series(pivot))
    graph_factor = [
        np.zeros_like(right) for _ in range(degree + 1)
    ]
    for order in range(degree + 1):
        for slack_degree in range(order + 1):
            graph_factor[order] += (
                boundary_slack[slack_degree]
                @ right
                @ inverse_root[order - slack_degree]
            )
    canonical_factor, factor_error = canonical_factor_series(
        repaired_slack,
        right,
    )
    if factor_error > 3e-8:
        raise RuntimeError(
            f"canonical factor reconstruction failed: {factor_error}"
        )
    return boundary_slack, graph_factor, canonical_factor


def transfer_coefficient(
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    grade: int,
) -> Matrix:
    """Return ``B_grade=W*(S*)^grade V``."""

    return (
        left.conj().T
        @ np.linalg.matrix_power(operator.conj().T, grade)
        @ right
    )


def rooted_column_lift(
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    grade: int,
) -> tuple[Matrix, Matrix, Matrix, Matrix]:
    """Return direct and predicted forms of ``C_k V*``."""

    direction = oriented_retightening_direction(
        operator,
        right,
        left,
        grade,
    )
    right_projection = right @ right.conj().T
    left_projection = left @ left.conj().T
    complement = np.eye(len(operator), dtype=complex) - right_projection
    transfer = transfer_coefficient(
        operator,
        right,
        left,
        grade,
    )
    bridge = (
        right_projection
        @ np.linalg.matrix_power(operator, grade)
        @ left_projection
    )
    predicted = -0.5 * bridge @ bridge.conj().T
    rooted_bracket = (
        np.linalg.matrix_power(operator, grade)
        @ bridge.conj().T
    )
    for earlier in range(1, grade):
        earlier_bridge = (
            right_projection
            @ np.linalg.matrix_power(operator, earlier)
            @ left_projection
        )
        rooted_bracket += (
            np.linalg.matrix_power(
                operator.conj().T,
                grade - earlier,
            )
            @ bridge
            @ earlier_bridge.conj().T
        )
    predicted -= 0.5 * complement @ rooted_bracket
    direct = direction.frame @ right.conj().T
    return direct, predicted, transfer, direction.frame


def evaluate_series(series: list[Matrix], parameter: float) -> Matrix:
    """Evaluate a finite matrix series."""

    result = np.zeros_like(series[0], dtype=complex)
    power = 1.0
    for coefficient in series:
        result += power * coefficient
        power *= parameter
    return result


def audit_case(
    construction_kind: str,
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    parameter_scale: float,
) -> FramePairingCausalityRecord:
    """Audit one colligation."""

    _, graph_factor, canonical_factor = graph_factor_series(
        operator,
        right,
        left,
        DEGREE,
    )
    graph_error = max(
        float(np.linalg.norm(graph - canonical))
        for graph, canonical in zip(
            graph_factor,
            canonical_factor,
            strict=True,
        )
    )

    rooted_error = 0.0
    delay_error = 0.0
    maximum_ratio = 0.0
    frame_motion = [
        coefficient.copy() for coefficient in graph_factor
    ]
    frame_motion[0] -= right
    evaluated_motion = evaluate_series(frame_motion, PARAMETER)
    for grade in range(1, MAXIMUM_GRADE + 1):
        direct, predicted, transfer, column = rooted_column_lift(
            operator,
            right,
            left,
            grade,
        )
        rooted_error = max(
            rooted_error,
            float(np.linalg.norm(direct - predicted)),
        )
        transfer_norm = float(np.linalg.norm(transfer))
        column_norm = float(np.linalg.norm(direct))
        if transfer_norm < 1e-11:
            delay_error = max(delay_error, column_norm)
            continue

        frame_cross = (
            evaluated_motion @ column.conj().T
            + column @ evaluated_motion.conj().T
        )
        weighted_cross = (
            PARAMETER ** (2 * grade) * frame_cross
        )
        weighted_transfer_norm = (
            PARAMETER ** grade * transfer_norm
        )
        maximum_ratio = max(
            maximum_ratio,
            float(np.linalg.norm(weighted_cross))
            / weighted_transfer_norm,
        )

    tolerance = 8e-8
    verified = bool(
        graph_error < tolerance
        and rooted_error < tolerance
        and delay_error < tolerance
        and np.isfinite(maximum_ratio)
    )
    if not verified:
        raise RuntimeError(
            "frame-pairing causality audit failed: "
            f"{construction_kind=}, {parameter_scale=}, "
            f"{graph_error=}, {rooted_error=}, {delay_error=}, "
            f"{maximum_ratio=}"
        )
    return FramePairingCausalityRecord(
        construction_kind=construction_kind,
        state_dimension=len(operator),
        defect_dimension=right.shape[1],
        parameter_scale=format_float(parameter_scale),
        graph_factor_error=format_float(graph_error),
        rooted_column_error=format_float(rooted_error),
        complete_delay_column_error=format_float(delay_error),
        maximum_weighted_frame_ratio=format_float(maximum_ratio),
        all_checks_passed=verified,
    )


def standard_records() -> list[FramePairingCausalityRecord]:
    """Return deterministic general, rank-chain, and delayed cases."""

    records = []
    for multiplicity in (1, 2, 3):
        operator, right, left = random_partial_isometry(
            4 * multiplicity + 5,
            multiplicity,
            np.random.default_rng(143_000 + multiplicity),
        )
        records.append(
            audit_case(
                "unstructured",
                operator,
                right,
                left,
                1,
            )
        )

    for multiplicity in (2, 3, 4):
        for parameter_scale in (1.0, 0.1, 0.01):
            operator, right, left, _, _ = rank_chain_case(
                multiplicity,
                143_100 + multiplicity,
                parameter_scale,
            )
            records.append(
                audit_case(
                    "rank_chain",
                    operator,
                    right,
                    left,
                    parameter_scale,
                )
            )

    generator = np.random.default_rng(143_200)
    for multiplicity in (1, 2, 3):
        operator, right, left = delayed_random_partial_isometry(
            4 * multiplicity,
            multiplicity,
            generator,
        )
        records.append(
            audit_case(
                "complete_first_delay",
                operator,
                right,
                left,
                1,
            )
        )
    return records


def write_records(
    records: list[FramePairingCausalityRecord],
    output: Path,
) -> str:
    """Write sorted JSON lines and return the SHA-256 digest."""

    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        json.dumps(asdict(record), sort_keys=True)
        for record in records
    ]
    payload = "\n".join(lines) + "\n"
    output.write_text(payload)
    return hashlib.sha256(payload.encode()).hexdigest()


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "experiments/"
            "repeated_crabb_frame_pairing_causality_s70226.jsonl"
        ),
    )
    return parser.parse_args()


def main() -> None:
    """Run the deterministic audit."""

    args = parse_args()
    records = standard_records()
    digest = write_records(records, args.output)
    print(
        json.dumps(
            {
                "records": len(records),
                "sha256": digest,
                "maximum_graph_factor_error": max(
                    float(record.graph_factor_error)
                    for record in records
                ),
                "maximum_rooted_column_error": max(
                    float(record.rooted_column_error)
                    for record in records
                ),
                "maximum_complete_delay_column_error": max(
                    float(record.complete_delay_column_error)
                    for record in records
                ),
                "maximum_weighted_frame_ratio": max(
                    float(record.maximum_weighted_frame_ratio)
                    for record in records
                ),
                "all_checks_passed": all(
                    record.all_checks_passed for record in records
                ),
            },
            sort_keys=True,
        )
    )


if __name__ == "__main__":
    main()
