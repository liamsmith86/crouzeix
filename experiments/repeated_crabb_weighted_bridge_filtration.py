#!/usr/bin/env python3
"""Audit elliptic bridge valuation in the affine preparation recurrence.

L298's grade-k metric and frame directions are rooted in the physical
bridge ideal generated by ``G_k=E S^k F`` and enter with degree
``2k``.  This checker constructs the actual canonical moving jets and
verifies that L299's complete six-term successor cannot appear before
degree ``2k+1`` and vanishes with the root transfer.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
import hashlib
import json
from pathlib import Path

import numpy as np

from crabb_block_hardy_equality import format_float
from repeated_crabb_boundary_metric_flag import rank_chain_case
from repeated_crabb_canonical_quintic_preimage import (
    canonical_factor_series,
    canonical_metric_slack_and_operator,
)
from repeated_crabb_delayed_jet import series_multiply
from repeated_crabb_oriented_retightening_transport import (
    oriented_retightening_direction,
)
from repeated_crabb_transfer_channel_covariance import (
    inflated_case,
    random_partial_isometry,
)


Matrix = np.ndarray
DEGREE = 9
PARAMETER = 0.05


@dataclass(frozen=True)
class WeightedBridgeFiltrationRecord:
    """One seed and successor filtration audit."""

    construction_kind: str
    state_dimension: int
    defect_dimension: int
    parameter_scale: str
    correction_grades: str
    first_nonzero_transfer_grade: int
    seed_root_error: str
    fixed_base_residual_norm: str
    successor_reconstruction_error: str
    premature_successor_norm: str
    vanished_root_successor_norm: str
    normalized_successor_norm: str
    all_checks_passed: bool


def zero_series(
    template: Matrix,
    degree: int = DEGREE,
) -> list[Matrix]:
    """Return a zero matrix series."""

    return [np.zeros_like(template) for _ in range(degree + 1)]


def constant_series(
    value: Matrix,
    degree: int = DEGREE,
) -> list[Matrix]:
    """Return a constant matrix series."""

    result = zero_series(value, degree)
    result[0] = value.copy()
    return result


def adjoint_series(series: list[Matrix]) -> list[Matrix]:
    """Return a coefficientwise adjoint series."""

    return [coefficient.conj().T for coefficient in series]


def add_series(
    *series: list[Matrix],
    scales: tuple[float, ...] | None = None,
) -> list[Matrix]:
    """Return a scaled sum of equally sized matrix series."""

    if not series:
        raise ValueError("at least one series is required")
    weights = scales or tuple(1.0 for _ in series)
    if len(weights) != len(series):
        raise ValueError("one scale is required per series")
    result = zero_series(series[0][0], len(series[0]) - 1)
    for weight, item in zip(weights, series, strict=True):
        for order, coefficient in enumerate(item):
            result[order] += weight * coefficient
    return result


def evaluate_series(series: list[Matrix], parameter: float) -> Matrix:
    """Evaluate a finite matrix series."""

    result = np.zeros_like(series[0], dtype=complex)
    power = 1.0
    for coefficient in series:
        result += power * coefficient
        power *= parameter
    return result


def transfer_coefficient(
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    grade: int,
) -> Matrix:
    """Return the grade-k transfer coefficient."""

    return (
        left.conj().T
        @ np.linalg.matrix_power(operator.conj().T, grade)
        @ right
    )


def seed_root_error(
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    grade: int,
) -> float:
    """Verify the sharp bridge-root formula for ``C_k V*``."""

    direction = oriented_retightening_direction(
        operator,
        right,
        left,
        grade,
    )
    right_projection = right @ right.conj().T
    left_projection = left @ left.conj().T
    complement = np.eye(len(operator), dtype=complex) - right_projection
    bridge = (
        right_projection
        @ np.linalg.matrix_power(operator, grade)
        @ left_projection
    )
    predicted = -0.5 * bridge @ bridge.conj().T
    bracket = (
        np.linalg.matrix_power(operator, grade)
        @ bridge.conj().T
    )
    for earlier in range(1, grade):
        earlier_bridge = (
            right_projection
            @ np.linalg.matrix_power(operator, earlier)
            @ left_projection
        )
        bracket += (
            np.linalg.matrix_power(
                operator.conj().T,
                grade - earlier,
            )
            @ bridge
            @ earlier_bridge.conj().T
        )
    predicted -= 0.5 * complement @ bracket
    return float(
        np.linalg.norm(
            direction.frame @ right.conj().T - predicted
        )
    )


def correction_series(
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    grades: tuple[int, ...],
) -> tuple[list[Matrix], list[Matrix], float]:
    """Return the weighted L298 metric/frame correction series."""

    metric = zero_series(operator)
    frame = zero_series(right)
    fixed_error = 0.0
    for grade in grades:
        direction = oriented_retightening_direction(
            operator,
            right,
            left,
            grade,
        )
        order = 2 * grade
        if order > DEGREE:
            continue
        metric[order] += direction.metric
        frame[order] += direction.frame
        fixed_error = max(
            fixed_error,
            float(
                np.linalg.norm(
                    direction.metric
                    - operator.conj().T
                    @ direction.metric
                    @ operator
                    - right @ direction.frame.conj().T
                    - direction.frame @ right.conj().T
                )
            ),
        )
    return metric, frame, fixed_error


def successor_series(
    base_operator: Matrix,
    moving_operator: list[Matrix],
    moving_frame: list[Matrix],
    metric: list[Matrix],
    frame: list[Matrix],
) -> list[Matrix]:
    """Return L299's complete six-term successor series."""

    delta = [coefficient.copy() for coefficient in moving_operator]
    delta[0] -= base_operator
    frame_motion = [
        coefficient.copy() for coefficient in moving_frame
    ]
    frame_motion[0] -= moving_frame[0]
    base = constant_series(base_operator)

    first = series_multiply(
        series_multiply(adjoint_series(delta), metric, DEGREE),
        base,
        DEGREE,
    )
    second = series_multiply(
        series_multiply(adjoint_series(base), metric, DEGREE),
        delta,
        DEGREE,
    )
    third = series_multiply(
        series_multiply(adjoint_series(delta), metric, DEGREE),
        delta,
        DEGREE,
    )
    fourth = series_multiply(
        frame_motion,
        adjoint_series(frame),
        DEGREE,
    )
    fifth = series_multiply(
        frame,
        adjoint_series(frame_motion),
        DEGREE,
    )
    sixth = series_multiply(
        frame,
        adjoint_series(frame),
        DEGREE,
    )
    return add_series(
        first,
        second,
        third,
        fourth,
        fifth,
        sixth,
        scales=(-1, -1, -1, -1, -1, -1),
    )


def first_nonzero_transfer_grade(
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    maximum_grade: int = 6,
) -> int:
    """Return the first numerically nonzero transfer grade."""

    for grade in range(1, maximum_grade + 1):
        if (
            np.linalg.norm(
                transfer_coefficient(
                    operator,
                    right,
                    left,
                    grade,
                )
            )
            > 1e-10
        ):
            return grade
    return maximum_grade + 1


def audit_case(
    construction_kind: str,
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    parameter_scale: float,
    grades: tuple[int, ...],
) -> WeightedBridgeFiltrationRecord:
    """Audit one mixed correction and its moving successor."""

    _, repaired_slack, moving_operator, _ = (
        canonical_metric_slack_and_operator(
            operator,
            right,
            left,
            DEGREE,
        )
    )
    moving_frame, factor_error = canonical_factor_series(
        repaired_slack,
        right,
    )
    metric, frame, fixed_error = correction_series(
        operator,
        right,
        left,
        grades,
    )
    successor = successor_series(
        operator,
        moving_operator,
        moving_frame,
        metric,
        frame,
    )

    moving_operator_value = evaluate_series(
        moving_operator,
        PARAMETER,
    )
    moving_frame_value = evaluate_series(
        moving_frame,
        PARAMETER,
    )
    metric_value = evaluate_series(metric, PARAMETER)
    frame_value = evaluate_series(frame, PARAMETER)
    delta_value = moving_operator_value - operator
    frame_motion_value = moving_frame_value - right
    direct_successor = -(
        delta_value.conj().T @ metric_value @ operator
        + operator.conj().T @ metric_value @ delta_value
        + delta_value.conj().T @ metric_value @ delta_value
        + frame_motion_value @ frame_value.conj().T
        + frame_value @ frame_motion_value.conj().T
        + frame_value @ frame_value.conj().T
    )
    reconstructed = evaluate_series(successor, PARAMETER)
    reconstruction_error = float(
        np.linalg.norm(direct_successor - reconstructed)
    )

    root_error = max(
        seed_root_error(operator, right, left, grade)
        for grade in grades
    )
    premature = 0.0
    vanished = 0.0
    weighted_transfer_size = 0.0
    for grade in grades:
        transfer = transfer_coefficient(
            operator,
            right,
            left,
            grade,
        )
        transfer_norm = float(np.linalg.norm(transfer))
        weighted_transfer_size += (
            PARAMETER ** (2 * grade) * transfer_norm
        )

        single_metric, single_frame, _ = correction_series(
            operator,
            right,
            left,
            (grade,),
        )
        single_successor = successor_series(
            operator,
            moving_operator,
            moving_frame,
            single_metric,
            single_frame,
        )
        premature = max(
            premature,
            max(
                (
                    float(np.linalg.norm(single_successor[order]))
                    for order in range(min(2 * grade + 1, DEGREE + 1))
                ),
                default=0.0,
            ),
        )
        if transfer_norm < 1e-10:
            vanished = max(
                vanished,
                max(
                    float(np.linalg.norm(coefficient))
                    for coefficient in single_successor
                ),
            )

    successor_norm = float(np.linalg.norm(reconstructed))
    normalized = (
        successor_norm / weighted_transfer_size
        if weighted_transfer_size > 1e-12
        else successor_norm
    )
    first_grade = first_nonzero_transfer_grade(
        operator,
        right,
        left,
    )

    tolerance = 2e-7
    verified = bool(
        factor_error < tolerance
        and root_error < tolerance
        and fixed_error < tolerance
        and reconstruction_error < tolerance
        and premature < tolerance
        and vanished < tolerance
        and np.isfinite(normalized)
        and normalized < 10
    )
    if not verified:
        raise RuntimeError(
            "weighted bridge filtration audit failed: "
            f"{construction_kind=}, {parameter_scale=}, "
            f"{factor_error=}, {root_error=}, {fixed_error=}, "
            f"{reconstruction_error=}, {premature=}, "
            f"{vanished=}, {normalized=}"
        )
    return WeightedBridgeFiltrationRecord(
        construction_kind=construction_kind,
        state_dimension=len(operator),
        defect_dimension=right.shape[1],
        parameter_scale=format_float(parameter_scale),
        correction_grades=",".join(str(grade) for grade in grades),
        first_nonzero_transfer_grade=first_grade,
        seed_root_error=format_float(root_error),
        fixed_base_residual_norm=format_float(fixed_error),
        successor_reconstruction_error=format_float(
            reconstruction_error
        ),
        premature_successor_norm=format_float(premature),
        vanished_root_successor_norm=format_float(vanished),
        normalized_successor_norm=format_float(normalized),
        all_checks_passed=verified,
    )


def standard_records() -> list[WeightedBridgeFiltrationRecord]:
    """Return deterministic general, rank-chain, and delayed cases."""

    records = []
    for multiplicity in (1, 2, 3):
        operator, right, left = random_partial_isometry(
            4 * multiplicity + 5,
            multiplicity,
            np.random.default_rng(144_000 + multiplicity),
        )
        records.append(
            audit_case(
                "unstructured",
                operator,
                right,
                left,
                1,
                (1, 2, 3),
            )
        )

    for multiplicity in (2, 3):
        for parameter_scale in (1.0, 0.1, 0.01):
            operator, right, left, _, _ = rank_chain_case(
                multiplicity,
                144_100 + multiplicity,
                parameter_scale,
            )
            records.append(
                audit_case(
                    "rank_chain",
                    operator,
                    right,
                    left,
                    parameter_scale,
                    (1, 2, 3),
                )
            )

    for delay in (1, 2, 3):
        operator, right, left, _ = inflated_case(
            9,
            2,
            delay + 1,
            2,
            144_200 + delay,
        )
        records.append(
            audit_case(
                f"complete_delay_{delay}",
                operator,
                right,
                left,
                1,
                tuple(range(1, min(delay + 2, 4))),
            )
        )
    return records


def write_records(
    records: list[WeightedBridgeFiltrationRecord],
    output: Path,
) -> str:
    """Write sorted JSON lines and return the SHA-256 digest."""

    output.parent.mkdir(parents=True, exist_ok=True)
    payload = "\n".join(
        json.dumps(asdict(record), sort_keys=True)
        for record in records
    ) + "\n"
    output.write_text(payload)
    return hashlib.sha256(payload.encode()).hexdigest()


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "experiments/"
            "repeated_crabb_weighted_bridge_filtration_s70226.jsonl"
        ),
    )
    return parser.parse_args()


def main() -> None:
    """Run the deterministic audit."""

    args = parse_args()
    records = standard_records()
    digest = write_records(records, args.output)
    print(
        json.dumps(
            {
                "records": len(records),
                "sha256": digest,
                "maximum_seed_root_error": max(
                    float(record.seed_root_error)
                    for record in records
                ),
                "maximum_premature_successor_norm": max(
                    float(record.premature_successor_norm)
                    for record in records
                ),
                "maximum_vanished_root_successor_norm": max(
                    float(record.vanished_root_successor_norm)
                    for record in records
                ),
                "maximum_normalized_successor_norm": max(
                    float(record.normalized_successor_norm)
                    for record in records
                ),
                "all_checks_passed": all(
                    record.all_checks_passed for record in records
                ),
            },
            sort_keys=True,
        )
    )


if __name__ == "__main__":
    main()
