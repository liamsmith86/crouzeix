#!/usr/bin/env python3
"""Audit the analytic chain-port balance from L245.

For an arbitrary polynomial functional calculus, every tail-to-chain
block and its return block are generated by the same retained operator.
The remote chain row has the unique physical multiplier ``2*c**r``.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
import hashlib
import json
from pathlib import Path

import numpy as np

from crabb_block_hardy_equality import format_float
from repeated_crabb_transfer_channel_covariance import (
    random_partial_isometry,
)


Matrix = np.ndarray


@dataclass(frozen=True)
class AnalyticChainPortBalanceRecord:
    """One deterministic functional-calculus port audit."""

    delay: int
    state_dimension: int
    defect_dimension: int
    maximum_incoming_error: str
    maximum_outgoing_error: str
    remote_multiplier_error: str
    ordinary_multiplier_error: str
    all_checks_passed: bool


def matrix_polynomial(matrix: Matrix, coefficients: tuple[complex, ...]) -> Matrix:
    """Evaluate a scalar polynomial by Horner's rule."""

    identity = np.eye(len(matrix), dtype=complex)
    result = np.zeros_like(matrix)
    for coefficient in reversed(coefficients):
        result = result @ matrix + coefficient * identity
    return result


def continuants(
    value: complex,
    ellipse_parameter: float,
    delay: int,
) -> list[complex]:
    """Return L237's scalar continuants through ``delay``."""

    result = [1 + 0j]
    if delay == 0:
        return result
    result.append(value)
    if delay == 1:
        return result
    result.append(value**2 - 2 * ellipse_parameter)
    for index in range(3, delay + 1):
        result.append(
            value * result[index - 1]
            - ellipse_parameter * result[index - 2]
        )
    return result


def delayed_pencil(
    delay: int,
    defect_dimension: int,
    seed: int,
    ellipse_parameter: float,
) -> tuple[Matrix, Matrix, Matrix, Matrix]:
    """Return the full pencil, tail pencil, tail defect, and inclusion."""

    tail_dimension = 2 * defect_dimension + 4
    tail, right, left = random_partial_isometry(
        tail_dimension,
        defect_dimension,
        np.random.default_rng(seed),
    )
    chain_dimension = delay * defect_dimension
    dimension = chain_dimension + tail_dimension
    chain = np.zeros((chain_dimension, chain_dimension), dtype=complex)
    for level in range(delay - 1):
        target = slice(
            (level + 1) * defect_dimension,
            (level + 2) * defect_dimension,
        )
        source = slice(
            level * defect_dimension,
            (level + 1) * defect_dimension,
        )
        chain[target, source] = np.eye(defect_dimension)

    partial = np.zeros((dimension, dimension), dtype=complex)
    partial[:chain_dimension, :chain_dimension] = chain
    partial[chain_dimension:, chain_dimension:] = tail
    last_chain = slice(
        chain_dimension - defect_dimension,
        chain_dimension,
    )
    partial[chain_dimension:, last_chain] = left

    right_full = np.zeros((dimension, defect_dimension), dtype=complex)
    right_full[chain_dimension:, :] = right
    final_full = np.zeros((dimension, defect_dimension), dtype=complex)
    final_full[:defect_dimension, :] = np.eye(defect_dimension)
    right_projection = right_full @ right_full.conj().T
    final_projection = final_full @ final_full.conj().T
    full_pencil = (
        partial
        + ellipse_parameter
        * (np.eye(dimension) + final_projection)
        @ partial.conj().T
        @ (np.eye(dimension) + right_projection)
    )

    tail_right_projection = right @ right.conj().T
    tail_pencil = (
        tail
        + ellipse_parameter
        * tail.conj().T
        @ (np.eye(tail_dimension) + tail_right_projection)
    )
    inclusion = np.zeros((dimension, tail_dimension), dtype=complex)
    inclusion[chain_dimension:, :] = np.eye(tail_dimension)
    return full_pencil, tail_pencil, left, inclusion


def cauchy_channels(
    tail_pencil: Matrix,
    left: Matrix,
    delay: int,
    ellipse_parameter: float,
    coefficients: tuple[complex, ...],
    radius: float,
    quadrature_order: int,
) -> list[Matrix]:
    """Reconstruct the common operators in L251 by Cauchy quadrature."""

    tail_dimension = len(tail_pencil)
    left_projection = left @ left.conj().T
    channels = [
        np.zeros((tail_dimension, tail_dimension), dtype=complex)
        for _ in range(delay)
    ]
    for index in range(quadrature_order):
        angle = 2 * np.pi * index / quadrature_order
        value = radius * np.exp(1j * angle)
        deltas = continuants(value, ellipse_parameter, delay)
        gamma = (
            2 * ellipse_parameter / value
            if delay == 1
            else ellipse_parameter * deltas[delay - 1] / deltas[delay]
        )
        retained = np.linalg.inv(
            value * np.eye(tail_dimension)
            - tail_pencil
            - gamma * left_projection
        )
        scalar_value = sum(
            coefficient * value**degree
            for degree, coefficient in enumerate(coefficients)
        )
        cauchy_weight = scalar_value * value / quadrature_order
        for row in range(delay):
            channels[row] += (
                cauchy_weight
                * deltas[row]
                / deltas[delay]
                * retained
            )
    return channels


def audit_delay(delay: int) -> AnalyticChainPortBalanceRecord:
    """Audit every chain row at one delay."""

    defect_dimension = 1 + delay % 2
    ellipse_parameter = 0.08 + 0.007 * delay
    coefficients = (
        0.0,
        1.0,
        -0.13 + 0.07j,
        0.09,
        -0.04j,
        0.017,
    )
    full_pencil, tail_pencil, left, inclusion = delayed_pencil(
        delay,
        defect_dimension,
        251_000 + delay,
        ellipse_parameter,
    )
    direct = matrix_polynomial(full_pencil, coefficients)
    radius = 1.4 + float(np.linalg.norm(full_pencil, 2))
    channels = cauchy_channels(
        tail_pencil,
        left,
        delay,
        ellipse_parameter,
        coefficients,
        radius,
        2048,
    )

    incoming_errors: list[float] = []
    outgoing_errors: list[float] = []
    multiplier_errors: list[float] = []
    for row, channel in enumerate(channels):
        chain_row = np.zeros(
            (len(full_pencil), defect_dimension),
            dtype=complex,
        )
        start = row * defect_dimension
        chain_row[start : start + defect_dimension, :] = np.eye(
            defect_dimension
        )
        incoming = inclusion.conj().T @ direct @ chain_row
        outgoing = chain_row.conj().T @ direct @ inclusion
        incoming_expected = channel @ left
        multiplier = 2 if row == 0 else 1
        outgoing_expected = (
            multiplier
            * ellipse_parameter ** (delay - row)
            * left.conj().T
            @ channel
        )
        incoming_errors.append(
            float(np.linalg.norm(incoming - incoming_expected))
        )
        outgoing_errors.append(
            float(np.linalg.norm(outgoing - outgoing_expected))
        )
        # The expected block already contains the proposed multiplier.
        # Keep this as an absolute residual: for the remote row at large
        # delay both sides are tiny, so dividing by the common channel
        # would turn harmless quadrature roundoff into an unstable ratio.
        multiplier_errors.append(outgoing_errors[-1])

    maximum_incoming = max(incoming_errors, default=0.0)
    maximum_outgoing = max(outgoing_errors, default=0.0)
    remote_multiplier = multiplier_errors[0]
    ordinary_multiplier = max(multiplier_errors[1:], default=0.0)
    tolerance = 3e-10
    verified = max(
        maximum_incoming,
        maximum_outgoing,
        remote_multiplier,
        ordinary_multiplier,
    ) < tolerance
    if not verified:
        raise RuntimeError(
            "the analytic chain-port audit failed: "
            f"delay={delay}, incoming={maximum_incoming:.3e}, "
            f"outgoing={maximum_outgoing:.3e}, "
            f"remote={remote_multiplier:.3e}, "
            f"ordinary={ordinary_multiplier:.3e}"
        )
    return AnalyticChainPortBalanceRecord(
        delay=delay,
        state_dimension=len(full_pencil),
        defect_dimension=defect_dimension,
        maximum_incoming_error=format_float(maximum_incoming),
        maximum_outgoing_error=format_float(maximum_outgoing),
        remote_multiplier_error=format_float(remote_multiplier),
        ordinary_multiplier_error=format_float(ordinary_multiplier),
        all_checks_passed=verified,
    )


def standard_records(
    maximum_delay: int,
) -> list[AnalyticChainPortBalanceRecord]:
    """Return deterministic audits through one delay."""

    return [audit_delay(delay) for delay in range(1, maximum_delay + 1)]


def write_records(
    records: list[AnalyticChainPortBalanceRecord],
    output: Path,
) -> str:
    """Write records atomically and return their SHA-256."""

    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8") as stream:
        for record in records:
            stream.write(json.dumps(asdict(record), sort_keys=True) + "\n")
    temporary.replace(output)
    return hashlib.sha256(output.read_bytes()).hexdigest()


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--maximum-delay", type=int, default=6)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "experiments/"
            "repeated_crabb_analytic_chain_port_balance_s70224.jsonl"
        ),
    )
    return parser.parse_args()


def main() -> None:
    """Run and persist the standard audit."""

    args = parse_args()
    records = standard_records(args.maximum_delay)
    digest = write_records(records, args.output)
    for record in records:
        print(json.dumps(asdict(record), sort_keys=True))
    print(json.dumps({"sha256": digest}, sort_keys=True))


if __name__ == "__main__":
    main()
