#!/usr/bin/env python3
"""Audit the constructive rooted-bridge response decomposition.

For a word term

    T = p (E S^j F) q = p V B_j* W* q,

the upper Stein endpoint of ``T+T*`` splits exactly into:

1. a rooted transfer-channel term; and
2. the balanced response of an explicit perpendicular column.

The column has norm at most ``(len(p)+1) ||B_j||_F`` and its state
lift remains in the two-sided ideal generated by ``E S^j F`` and its
adjoint.  The checker also verifies that the rooted terms cancel for
relative commutators.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
import hashlib
import json
from pathlib import Path

import numpy as np

from crabb_block_hardy_equality import format_float
from repeated_crabb_boundary_metric_flag import rank_chain_case
from repeated_crabb_elliptic_cokernel import stein_inverse
from repeated_crabb_endpoint_null_gauge import (
    delayed_random_partial_isometry,
)
from repeated_crabb_transfer_channel_covariance import (
    random_partial_isometry,
)


Matrix = np.ndarray


@dataclass(frozen=True)
class RootedBridgeFluxRecord:
    """One numerical audit of the rooted bridge formula."""

    construction_kind: str
    state_dimension: int
    defect_dimension: int
    delay: int
    prefix: str
    suffix: str
    transfer_norm: str
    endpoint_split_error: str
    perpendicular_column_error: str
    ideal_lift_reconstruction_error: str
    column_norm: str
    column_bound_slack: str
    relative_root_cancellation_error: str
    relative_response_error: str
    all_checks_passed: bool


def word_value(word: str, operator: Matrix) -> Matrix:
    """Evaluate a word in ``s=S`` and ``a=S*``."""

    result = np.eye(len(operator), dtype=complex)
    adjoint = operator.conj().T
    for letter in word:
        result = result @ (operator if letter == "s" else adjoint)
    return result


def transfer_channel(
    copy_matrix: Matrix,
    operator: Matrix,
    right: Matrix,
    left: Matrix,
) -> Matrix:
    """Return ``Phi(copy_matrix)`` through one Stein solve."""

    state_gram = linear_stein_inverse(
        operator,
        right @ copy_matrix @ right.conj().T,
    )
    return left.conj().T @ state_gram @ left


def linear_stein_inverse(
    operator: Matrix,
    forcing: Matrix,
) -> Matrix:
    """Apply the complex-linear Stein inverse to any forcing."""

    hermitian_real = (forcing + forcing.conj().T) / 2
    hermitian_imaginary = (forcing - forcing.conj().T) / (2j)
    return (
        stein_inverse(operator, hermitian_real)
        + 1j * stein_inverse(operator, hermitian_imaginary)
    )


def response_endpoint(
    column: Matrix,
    operator: Matrix,
    right: Matrix,
    left: Matrix,
) -> Matrix:
    """Return the balanced perpendicular-column response."""

    forcing = (
        right @ column.conj().T
        + column @ right.conj().T
    )
    response = stein_inverse(operator, forcing)
    return left.conj().T @ response @ left


def rooted_bridge_split(
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    delay: int,
    prefix: str,
    suffix: str,
) -> tuple[Matrix, Matrix, Matrix, Matrix, Matrix]:
    """Return ``T``, its rooted endpoint, column, bridge, and lift.

    The returned lift is an independent reconstruction of
    ``column @ right*`` from products containing the physical bridge
    or its adjoint.
    """

    prefix_value = word_value(prefix, operator)
    suffix_value = word_value(suffix, operator)
    transfer = (
        left.conj().T
        @ np.linalg.matrix_power(operator.conj().T, delay)
        @ right
    )
    bridge = right @ transfer.conj().T @ left.conj().T
    bridge_adjoint = bridge.conj().T
    right_projection = right @ right.conj().T
    complement = np.eye(len(operator), dtype=complex) - right_projection

    term = prefix_value @ bridge @ suffix_value
    copy_root = (
        transfer.conj().T
        @ left.conj().T
        @ suffix_value
        @ prefix_value
        @ right
    )
    rooted_endpoint = transfer_channel(
        copy_root,
        operator,
        right,
        left,
    )

    column = (
        complement
        @ prefix_value.conj().T
        @ suffix_value.conj().T
        @ left
        @ transfer
    )
    lifted_column = (
        complement
        @ prefix_value.conj().T
        @ suffix_value.conj().T
        @ bridge_adjoint
    )

    for index, letter in enumerate(prefix):
        left_word = word_value(prefix[:index], operator)
        right_word = word_value(prefix[index + 1 :], operator)
        if letter == "a":
            contribution = (
                operator.conj().T
                @ right_word
                @ bridge
                @ suffix_value
                @ left_word
                @ right
            )
            lifted_contribution = (
                operator.conj().T
                @ right_word
                @ bridge
                @ suffix_value
                @ left_word
                @ right_projection
            )
        else:
            contribution = -(
                operator.conj().T
                @ left_word.conj().T
                @ suffix_value.conj().T
                @ bridge_adjoint
                @ right_word.conj().T
                @ right
            )
            lifted_contribution = -(
                operator.conj().T
                @ left_word.conj().T
                @ suffix_value.conj().T
                @ bridge_adjoint
                @ right_word.conj().T
                @ right_projection
            )
        column = column + contribution
        lifted_column = lifted_column + lifted_contribution

    return term, rooted_endpoint, column, bridge, lifted_column


def audit_case(
    construction_kind: str,
    operator: Matrix,
    right: Matrix,
    left: Matrix,
    delay: int,
    prefix: str,
    suffix: str,
) -> RootedBridgeFluxRecord:
    """Audit one rooted term and one relative commutator."""

    (
        term,
        rooted_endpoint,
        column,
        _,
        lifted_column,
    ) = rooted_bridge_split(
        operator,
        right,
        left,
        delay,
        prefix,
        suffix,
    )
    upper_endpoint = (
        left.conj().T
        @ stein_inverse(operator, term + term.conj().T)
        @ left
    )
    predicted_endpoint = (
        rooted_endpoint
        + rooted_endpoint.conj().T
        + response_endpoint(column, operator, right, left)
    )

    transfer = (
        left.conj().T
        @ np.linalg.matrix_power(operator.conj().T, delay)
        @ right
    )
    transfer_norm = float(np.linalg.norm(transfer))
    column_norm = float(np.linalg.norm(column))
    column_bound = (len(prefix) + 1) * transfer_norm

    letter = "s" if (len(prefix) + len(suffix) + delay) % 2 else "a"
    letter_value = word_value(letter, operator)
    (
        left_term,
        left_root,
        left_column,
        _,
        _,
    ) = rooted_bridge_split(
        operator,
        right,
        left,
        delay,
        letter + prefix,
        suffix,
    )
    (
        right_term,
        right_root,
        right_column,
        _,
        _,
    ) = rooted_bridge_split(
        operator,
        right,
        left,
        delay,
        prefix,
        suffix + letter,
    )
    relative_term = left_term - right_term
    direct_relative = letter_value @ term - term @ letter_value
    relative_endpoint = (
        left.conj().T
        @ stein_inverse(
            operator,
            relative_term + relative_term.conj().T,
        )
        @ left
    )
    predicted_relative = response_endpoint(
        left_column - right_column,
        operator,
        right,
        left,
    )

    endpoint_error = float(
        np.linalg.norm(upper_endpoint - predicted_endpoint)
    )
    perpendicular_error = float(
        np.linalg.norm(right.conj().T @ column)
    )
    lift_error = float(
        np.linalg.norm(
            column @ right.conj().T - lifted_column
        )
    )
    root_cancellation_error = float(
        max(
            np.linalg.norm(left_root - right_root),
            np.linalg.norm(relative_term - direct_relative),
        )
    )
    relative_response_error = float(
        np.linalg.norm(relative_endpoint - predicted_relative)
    )
    bound_slack = column_bound - column_norm

    tolerance = 2e-8
    verified = bool(
        endpoint_error < tolerance
        and perpendicular_error < tolerance
        and lift_error < tolerance
        and bound_slack > -tolerance
        and root_cancellation_error < tolerance
        and relative_response_error < tolerance
    )
    if not verified:
        raise RuntimeError(
            "the rooted bridge flux audit failed: "
            f"{construction_kind=}, {delay=}, {prefix=}, {suffix=}, "
            f"{endpoint_error=}, {perpendicular_error=}, "
            f"{lift_error=}, {bound_slack=}, "
            f"{root_cancellation_error=}, "
            f"{relative_response_error=}"
        )

    return RootedBridgeFluxRecord(
        construction_kind=construction_kind,
        state_dimension=len(operator),
        defect_dimension=right.shape[1],
        delay=delay,
        prefix=prefix or "1",
        suffix=suffix or "1",
        transfer_norm=format_float(transfer_norm),
        endpoint_split_error=format_float(endpoint_error),
        perpendicular_column_error=format_float(
            perpendicular_error
        ),
        ideal_lift_reconstruction_error=format_float(lift_error),
        column_norm=format_float(column_norm),
        column_bound_slack=format_float(bound_slack),
        relative_root_cancellation_error=format_float(
            root_cancellation_error
        ),
        relative_response_error=format_float(
            relative_response_error
        ),
        all_checks_passed=verified,
    )


def standard_records() -> list[RootedBridgeFluxRecord]:
    """Return deterministic general, rank-chain, and delayed audits."""

    word_cases = (
        (1, "", ""),
        (1, "a", "a"),
        (2, "aa", "a"),
        (3, "sa", "aa"),
        (1, "aaa", "aaa"),
    )
    records = []
    for multiplicity in range(1, 5):
        operator, right, left = random_partial_isometry(
            3 * multiplicity + 5,
            multiplicity,
            np.random.default_rng(141_000 + multiplicity),
        )
        for delay, prefix, suffix in word_cases:
            records.append(
                audit_case(
                    "unstructured",
                    operator,
                    right,
                    left,
                    delay,
                    prefix,
                    suffix,
                )
            )

    for multiplicity in (2, 3, 4):
        operator, right, left, _, _ = rank_chain_case(
            multiplicity,
            141_100 + multiplicity,
            0.1,
        )
        for delay, prefix, suffix in word_cases[:4]:
            records.append(
                audit_case(
                    "rank_chain",
                    operator,
                    right,
                    left,
                    delay,
                    prefix,
                    suffix,
                )
            )

    generator = np.random.default_rng(141_200)
    for multiplicity in (2, 3):
        operator, right, left = delayed_random_partial_isometry(
            4 * multiplicity,
            multiplicity,
            generator,
        )
        for delay, prefix, suffix in word_cases[:3]:
            records.append(
                audit_case(
                    "complete_first_delay",
                    operator,
                    right,
                    left,
                    delay,
                    prefix,
                    suffix,
                )
            )
    return records


def write_records(
    records: list[RootedBridgeFluxRecord],
    output: Path,
) -> str:
    """Write deterministic JSON Lines atomically and return its hash."""

    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8") as stream:
        for record in records:
            stream.write(json.dumps(asdict(record), sort_keys=True) + "\n")
    temporary.replace(output)
    return hashlib.sha256(output.read_bytes()).hexdigest()


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "experiments/"
            "repeated_crabb_rooted_bridge_flux_s70226.jsonl"
        ),
    )
    return parser.parse_args()


def main() -> None:
    """Run and persist the rooted bridge audit."""

    args = parse_args()
    records = standard_records()
    digest = write_records(records, args.output)
    for record in records:
        print(json.dumps(asdict(record), sort_keys=True))
    print(json.dumps({"sha256": digest}, sort_keys=True))


if __name__ == "__main__":
    main()
